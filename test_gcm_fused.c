#include <openssl/evp.h>
#include <openssl/err.h>
#include <string.h>
#include <stdio.h>
#include <stdlib.h>

/* Test with NIST GCM test vector #3: 64 bytes of plaintext */
int main(void)
{
    const unsigned char key[] = {
        0xfe, 0xff, 0xe9, 0x92, 0x86, 0x65, 0x73, 0x1c,
        0x6d, 0x6a, 0x8f, 0x94, 0x67, 0x30, 0x83, 0x08
    };
    const unsigned char iv[] = {
        0xca, 0xfe, 0xba, 0xbe, 0xfa, 0xce, 0xdb, 0xad,
        0xde, 0xca, 0xf8, 0x88
    };
    const unsigned char pt[] = {
        0xd9, 0x31, 0x32, 0x25, 0xf8, 0x84, 0x06, 0xe5,
        0xa5, 0x59, 0x09, 0xc5, 0xaf, 0xf5, 0x26, 0x9a,
        0x86, 0xa7, 0xa9, 0x53, 0x15, 0x34, 0xf7, 0xda,
        0x2e, 0x4c, 0x30, 0x3d, 0x8a, 0x31, 0x8a, 0x72,
        0x1c, 0x3c, 0x0c, 0x95, 0x95, 0x68, 0x09, 0x53,
        0x2f, 0xcf, 0x0e, 0x24, 0x49, 0xa6, 0xb5, 0x25,
        0xb1, 0x6a, 0xed, 0xf5, 0xaa, 0x0d, 0xe6, 0x57,
        0xba, 0x63, 0x7b, 0x39, 0x1a, 0xaf, 0xd2, 0x55
    };
    const unsigned char expected_ct[] = {
        0x42, 0x83, 0x1e, 0xc2, 0x21, 0x77, 0x74, 0x24,
        0x4b, 0x72, 0x21, 0xb7, 0x84, 0xd0, 0xd4, 0x9c,
        0xe3, 0xaa, 0x21, 0x2f, 0x2c, 0x02, 0xa4, 0xe0,
        0x35, 0xc1, 0x7e, 0x23, 0x29, 0xac, 0xa1, 0x2e,
        0x21, 0xd5, 0x14, 0xb2, 0x54, 0x66, 0x93, 0x1c,
        0x7d, 0x8f, 0x6a, 0x5a, 0xac, 0x84, 0xaa, 0x05,
        0x1b, 0xa3, 0x0b, 0x39, 0x6a, 0x0a, 0xac, 0x97,
        0x3d, 0x58, 0xe0, 0x91, 0x47, 0x3f, 0x59, 0x85
    };
    const unsigned char expected_tag[] = {
        0x4d, 0x5c, 0x2a, 0xf3, 0x27, 0xcd, 0x64, 0xa6,
        0x2c, 0xf3, 0x5a, 0xbd, 0x2b, 0xa6, 0xfa, 0xb4
    };

    unsigned char *ct = malloc(64);
    unsigned char *tag_buf = malloc(16);
    unsigned char tag[16];
    int len, ct_len;
    EVP_CIPHER_CTX *ctx;

    printf("Testing fused AES-128-GCM (64B plaintext)...\n");
    printf("pt=%p ct=%p key=%p\n", pt, ct, key);
    
    /* First test: 64 bytes, may go through fused path */
    ctx = EVP_CIPHER_CTX_new();
    EVP_EncryptInit_ex(ctx, EVP_aes_128_gcm(), NULL, NULL, NULL);
    EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_SET_IVLEN, 12, NULL);
    EVP_EncryptInit_ex(ctx, NULL, NULL, key, iv);
    EVP_EncryptUpdate(ctx, ct, &len, pt, 64);
    ct_len = len;
    EVP_EncryptFinal_ex(ctx, ct + len, &len);
    ct_len += len;
    EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_GET_TAG, 16, tag);
    EVP_CIPHER_CTX_free(ctx);

    printf("CT len: %d\n", ct_len);
    if (memcmp(ct, expected_ct, 64) != 0) {
        printf("FAIL: ciphertext mismatch!\n");
        printf("Expected:\n");
        for (int i = 0; i < 64; i++) printf("%02x", expected_ct[i]);
        printf("\nGot:\n");
        for (int i = 0; i < 64; i++) printf("%02x", ct[i]);
        printf("\n");
        return 1;
    }
    if (memcmp(tag, expected_tag, 16) != 0) {
        printf("FAIL: tag mismatch!\n");
        printf("Expected:\n");
        for (int i = 0; i < 16; i++) printf("%02x", expected_tag[i]);
        printf("\nGot:\n");
        for (int i = 0; i < 16; i++) printf("%02x", tag[i]);
        printf("\n");
        return 1;
    }
    printf("PASS\n");
    return 0;
}
